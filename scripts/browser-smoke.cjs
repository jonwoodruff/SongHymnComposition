const { chromium }=require('playwright');
const assert=require('node:assert/strict');
const base=process.env.BROWSER_TEST_URL;
if(!base) throw new Error('Run this through scripts/browser_smoke.py against its isolated database.');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const a=await browser.newContext({viewport:{width:1440,height:1100}}), r=await browser.newContext({viewport:{width:1440,height:1100}});
 const page=await a.newPage(), other=await r.newPage();const errors=[];
 for(const p of [page,other])p.on('pageerror',e=>errors.push(e.message));
 async function login(p,user){await p.goto(`${base}/accounts/login/`);await p.locator('[name=username]').fill(user);await p.locator('[name=password]').fill('browser-only-password');await p.getByRole('button',{name:'Sign in',exact:true}).click();await p.goto(`${base}/songs/1/`);}
 await login(page,'browserauthor');await login(other,'browserreviewer');
 await page.locator('#part-concept summary').first().click();
 await page.locator('#content-concept').fill('A hopeful song for the gathering.\nA recurring promise in every verse.');
 await page.waitForFunction(()=>document.querySelector('#part-concept .editor-status').textContent==='All changes saved');
 await other.waitForFunction(()=>document.querySelector('#part-concept .prose').textContent.includes('A hopeful song'));
 assert.equal(page.url(),`${base}/songs/1/`);
 console.log('PASS autosave and live update to second session');
 await other.locator('#part-concept summary').first().click();
 await other.waitForFunction(()=>document.querySelector('#content-concept').readOnly);
 assert.match(await other.locator('#part-concept .presence').innerText(),/browserauthor/);
 console.log('PASS other editor sees presence and protected text');
 await other.locator('#part-lyrics summary').first().click();
 await other.locator('#content-lyrics').fill('We sing together in the morning light.');
 await other.waitForFunction(()=>document.querySelector('#part-lyrics .editor-status').textContent==='All changes saved');
 await page.waitForFunction(()=>document.querySelector('#part-lyrics .prose').textContent.includes('morning light'));
 console.log('PASS different sections edit independently');
 await page.locator('#comment-scope').selectOption('lyrics');await page.locator('#comment-anchor').fill('morning light');
 await page.locator('#comment-form [name=body]').fill('Could this phrase return in the chorus?');
 await page.getByRole('button',{name:'Share thought'}).click();
 await other.waitForFunction(()=>document.querySelector('#comment-list').textContent.includes('Could this phrase'));
 await other.waitForFunction(()=>document.querySelector('#part-lyrics mark')?.textContent==='morning light');
 await other.locator('#part-lyrics mark').click();
 assert.equal(await other.locator('#comment-list .is-focused').count(),1);
 await other.getByRole('button',{name:'Collapse all'}).click();
 assert.equal(await other.locator('#comment-list details[open]').count(),0);
 console.log('PASS live comments, phrase markers, collapse and focus');
 await page.locator('#part-concept summary').first().click();
 await other.waitForFunction(()=>!document.querySelector('#content-concept').readOnly);
 await other.locator('#content-concept').fill('Reviewer can continue after author closes editor.');
 await other.waitForFunction(()=>document.querySelector('#part-concept .editor-status').textContent==='All changes saved');
 console.log('PASS editor handoff');
 await page.locator('#part-tune summary').first().click();
 await page.locator('#part-tune .note-buttons button').filter({hasText:/^C$/}).click();
 await page.locator('#part-tune .note-buttons button').filter({hasText:/^D$/}).click();
 await page.waitForFunction(()=>document.querySelector('#part-tune .editor-status').textContent==='All changes saved');
 await other.waitForFunction(()=>document.querySelector('#part-tune .music-display svg'));
 console.log('PASS melody buttons autosave and notation refresh');
 await page.screenshot({path:`${process.env.BROWSER_OUTPUT_DIR}/desktop.png`,fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:`${process.env.BROWSER_OUTPUT_DIR}/mobile.png`,fullPage:true});
 console.log('PASS mobile width');
 assert.deepEqual(errors,[]);console.log('PASS no browser JavaScript errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
